-- coupon_stocks 의 시각을 발급건·이력과 같은 정밀도로 맞춥니다.
--
-- V1(재고 정합)이 coupon_stocks.updated_at 을 asOf 와 직접 비교하는데, 이 컬럼만
-- datetime(0) 이라 소수 초가 **반올림**돼 저장됩니다. 12:00:00.600000 에 재고가 갱신되면
-- 12:00:01 로 굳고, asOf 를 12:00:00.900000 로 잡아도 12:00:01 > asOf 가 되어
-- 실행 자체가 거부됩니다 — 데이터는 정상인데 게이트가 못 돕니다.
--
-- 반대 방향도 있습니다. asOf 이후 0.4초에 일어난 진짜 갱신은 12:00:00 으로 내려가
-- 가드를 통과하고, V1 이 움직인 재고와 비교해 재실행마다 다른 답을 냅니다.
--
-- V2026082502__issuance_usage_precision.sql 이 issuance_usages 에 대해 고친 것과 같은 버그입니다.
--
-- ⚠️ 이미 반올림돼 굳은 값은 타입을 넓혀도 복구되지 않습니다. 재시드가 필요합니다.
-- ⚠️ 게이트가 도는 CLEAN/CORRUPT 스키마는 시드 저장소가 자기 DDL 로 만듭니다 —
--    그쪽 coupon_stocks 정의도 함께 고쳐야 같은 문제가 안 납니다.
-- ⚠️ 테이블 재구축이라 잠금이 걸립니다. 적재 전에 돌리십시오.

ALTER TABLE `coupon_stocks`
    MODIFY `updated_at` datetime(6) NOT NULL COMMENT '재고 변경 시각. 발급건·이력과 같은 정밀도';
