package com.kafkick.core.benchmark;

/**
 * 회차의 성격. 저장 전략과 데이터 취급이 갈린다.
 *
 * <p>세 값을 스키마에 남기는 이유는 나중에 회차 목록만 보고 "이건 왜 수치가 이상한가" 를
 * 판단할 수 있어야 하기 때문이다. WARMUP 을 구분하지 않으면 버려야 할 회차가 비교표에 섞인다.
 */
public enum BenchmarkRunType {

    /**
     * 데이터를 버리는 회차. JVM 이 회차마다 새로 뜨지 않아 첫 회차만 JIT·풀이 차갑고,
     * 그 차가움이 v1 에만 붙으면 세 버전 비교가 거짓이 된다.
     */
    WARMUP,

    MAIN,

    /**
     * 앱을 죽여 보는 회차. <b>메모리 버퍼를 쓰지 않는다</b> — 앱이 죽는 순간 버퍼가 사라지는데,
     * 앱을 죽이는 게 이 회차의 목적이다. 회차 메타는 명령마다 곧바로 DB 에 쓰고, 시계열은
     * Prometheus 가 이미 긁어둔 것을 종료 후에 뽑는다.
     */
    CHAOS
}
