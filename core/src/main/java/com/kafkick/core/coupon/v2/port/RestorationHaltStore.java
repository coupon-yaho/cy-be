package com.kafkick.core.coupon.v2.port;

/**
 * 재고 복원이 상한 초과({@code -2})로 거절된 회차의 표식.
 *
 * <p><b>프로세스 밖에 둔다.</b> 복원을 부르는 곳은 취소·사용취소(api)와 만료 배치(batch)로
 * 갈려 있고, 표식을 읽는 곳은 만료 배치다. 인메모리로 두면 취소가 본 {@code -2} 를 배치가
 * 모르고, 배치를 두 대 띄우면 한 대만 멈춘다 — 방어가 배포 토폴로지에 달리게 된다.
 *
 * <p><b>해제는 재구성이 한다.</b> 표식은 "Redis 재고가 DB 와 어긋나 있다" 는 뜻이고 그것을
 * 되돌리는 유일한 절차가 재구성·워밍업이다. 그 절차가 회차의 카운터를 다시 쓰면서 이 표식도
 * 함께 지운다 — 사람이 따로 눌러야 하는 버튼을 만들면 "고쳤는데 안 풀린다" 가 된다.
 *
 * <p><b>해제와 표식 쓰기 사이에 원자성이 없다.</b> 시딩이 표식을 푼 뒤 뒤늦은 {@code -2} 가
 * 도착하면 표식이 되살아나고, 재고는 정상인데 그 회차 만료만 멈춘 채 남는다. 이 창은
 * <b>절차가 닫는다</b> — 재구성은 게이트를 닫고 진행 중인 복원이 빠진 뒤에 시딩한다(07).
 * 세대 번호로 코드가 닫으려면 {@code meta} 에 필드가 하나 늘고 Lua 5종과 인자 가드(12)가
 * 함께 움직인다. 그 크기를 감수할 이유가 아직 없다.
 *
 * <p><b>읽는 곳은 만료 배치뿐이다.</b> 취소·사용취소는 표식을 <b>세우기만 하고 자기는 계속
 * 간다</b> — 사람이 누른 취소를 막는 것은 재고를 지키는 것이 아니라 사용자를 막는 것이고,
 * 그 어긋남은 건당 1장이라 배치가 초당 수백 건을 미는 것과 속도가 다르다. 정합성은 어느
 * 쪽이든 재구성이 DB 에서 다시 계산해 맞춘다.
 */
public interface RestorationHaltStore {

    /** 그 회차의 복원을 멈춘다. 이미 멈춰 있으면 아무 일도 없다. */
    void halt(long couponRoundId);

    /** @return 그 회차가 멈춰 있으면 참 */
    boolean isHalted(long couponRoundId);

    /** 표식을 지운다. 재구성·워밍업이 카운터를 다시 쓸 때 함께 부른다. */
    void clear(long couponRoundId);
}
