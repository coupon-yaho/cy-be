package com.kafkick.infra.mq.config;

/**
 * 프로비저닝 한 번의 결과. <b>실패를 두 종류로 가른다</b> — 대응이 정반대이기 때문이다.
 *
 * <p>예전에는 "브로커에 닿았는가" 로 갈랐는데 그게 틀렸다. 브로커에 닿았는데도 재시도가 고쳐 주는
 * 실패가 있다 — 롤링 재기동 중 한 대가 아직 안 올라왔으면 {@code CreateTopics} 가 RF3 을 만족하지
 * 못해 실패하지만, 남은 두 대가 응답하므로 "닿았다" 로 읽힌다. 그 상태에서 재시도를 끊으면
 * 토픽이 없는 채로 발급이 시작되고 브로커가 RF1 짜리를 대신 만든다.
 */
public enum ProvisionOutcome {

    /** 선언대로 존재함을 확인했다. */
    PROVISIONED,

    /** 브로커에 있는 토픽이 선언과 다르다. <b>재시도가 고치지 못한다</b> — 복제본 수는 재배치로만 바뀐다. */
    MISMATCHED,

    /** 아직 확인하지 못했다(미접속 · 생성 실패 · 조회 타임아웃). 재시도가 의미 있다. */
    UNCONFIRMED
}
