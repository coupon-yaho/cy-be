package com.kafkick.batch.coupon.v2;

/**
 * 재구성 한 번의 결말. 워밍업과 <b>enum 을 나눈다</b> — 두 경로는 "이미 열려 있음" 을 정반대로
 * 판정하므로(워밍업은 사고, 재구성은 정상 입력), 한 타입에 섞으면 어느 쪽에서 안 나오는 값을
 * 호출부가 매번 되짚어야 한다.
 */
public enum CouponRoundRebuildStatus {

    /**
     * 게이트를 닫고, 카운터 네 값을 DB 집계로 다시 세우고, {@code meta} 로 다시 열었다.
     * 끝난 시점의 {@code HLEN} 과 {@code issued_ever} 는 같고 {@code stock} 은 4′ 재집계
     * 기준이다.
     */
    REBUILT,

    /**
     * 같은 회차의 게이트 쓰기(재구성이든 워밍업이든)가 이 인스턴스에서 이미 돌고 있다.
     *
     * <p><b>batch 가 1대라는 사실은 이것을 막지 못한다.</b> 트리거가 HTTP 라 워커 스레드가
     * 여럿이고, 07 이 그린 겹침 시퀀스는 프로세스 수가 아니라 <b>실행의 겹침</b>으로 성립한다.
     */
    REBUILD_IN_PROGRESS,

    /**
     * 확인 토큰이 회차 번호와 다르다. <b>아무것도 읽지 않고 돌아간다</b> — 게이트를 닫기
     * 한참 전이다. 부하 중에 눌리는 사고를 막는 유일한 사람 확인 절차라 실패를 400 으로 낸다.
     */
    CONFIRMATION_MISMATCH,

    /** 회차 행이 없다. */
    ROUND_NOT_FOUND,

    /** {@code coupon_stocks} 행이 없다. 총재고를 모르면 {@code stock} 도 {@code meta} 도 못 쓴다. */
    STOCK_ROW_MISSING,

    /** 회차 엔진이 V2 가 아니다. v1 회차에 v2 키를 올리면 아무도 안 읽는 카운터가 생긴다. */
    ENGINE_NOT_V2,

    /**
     * 게이트를 닫은 뒤 <b>예상하지 못한 실패</b>로 멈췄다 — 재고 행이 사라졌거나, drain 대기가
     * 끊겼거나, DB 가 답하지 않았다.
     *
     * <p>이 결말을 예외로 흘려보내면 500 이 나가고, 그 순간 <b>게이트가 닫혔다는 사실이
     * 응답에서 사라진다</b>. 운영자는 서버 오류로 읽고 다시 누르거나 손을 떼는데, 실제로는 그
     * 회차가 이미 전면 503 이다. 원인은 로그에 스택으로 남기고, 응답에는 "닫힌 채 멈췄다" 를
     * 남기는 것이 이 값의 전부다.
     */
    REBUILD_FAILED,

    /**
     * 활성 건수가 총재고를 넘는다 — DB 에 이미 §9.1 I1(초과 발급) 위반이 있다.
     *
     * <p>사전 점검을 게이트를 닫기 <b>전에</b> 한 번 돌리므로 흔한 경우는 거기서 걸리고, 그때는
     * 그 회차의 발급이 한 건도 멈추지 않는다. 닫은 뒤의 집계나 4′ 재집계에서 처음 드러나면 그
     * 회차는 멈춘 채 남는다 — 음수 {@code stock} 위에 게이트를 다시 여는 것보다 낫다. 그쪽은
     * 선점 Lua 가 {@code -5}(매진)로 읽어 <b>초과 발급을 정상 상태처럼</b> 굳힌다. DB 를 고친 뒤
     * 다시 돌리는 것이 복구 절차다.
     *
     * <p><b>둘을 가르는 것은 이 이름이 아니라 {@code gateClosed} 다.</b> 게이트를 닫은 뒤에
     * 끝나는 거절은 이것 말고도 있다({@code STOCK_ROW_MISSING}·{@code ENGINE_NOT_V2}·
     * {@code ROUND_NOT_FOUND} 가 그 뒤 단계에서 나오는 경우). 상태 이름으로 그 사실을 읽으려
     * 들면 언젠가 틀린다.
     */
    OVER_ISSUED_ROUND
}
